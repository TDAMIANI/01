# 5. Crear un arreglo de números aleatorios de longitud 100 y obtener su media y varianza
random_array = np.random.rand(100)
mean = np.mean(random_array)
variance = np.var(random_array)
print(mean)
print(variance)

# 6. Calcular la media de un arreglo usando np.sum
array_mean = np.array([1, 2, 3, 4, 5])
mean_calculated = np.sum(array_mean) / array_mean.size
print(mean_calculated)

## Calcular la varianza de un arreglo usando np.sum y np.mean
array_variance = np.array([1, 2, 3, 4, 5])
mean_array = np.mean(array_variance)
variance_calculated = np.sum((array_variance - mean_array) ** 2) / array_variance.size
print(array_variance)
print(mean_array)
print(variance_calculated)

